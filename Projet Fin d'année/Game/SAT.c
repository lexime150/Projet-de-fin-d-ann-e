#include "SAT.h"
#include <float.h>   /* FLT_MAX */
#include <math.h>

/* ???????????????????????????????????????????????????????????????????
   Helpers vectoriels internes
??????????????????????????????????????????????????????????????????? */

static float Vec2Dot(sfVector2f a, sfVector2f b)
{
    return a.x * b.x + a.y * b.y;
}

static sfVector2f Vec2Sub(sfVector2f a, sfVector2f b)
{
    return (sfVector2f) { a.x - b.x, a.y - b.y };
}

static sfVector2f Vec2Normalize(sfVector2f v)
{
    float len = sqrtf(v.x * v.x + v.y * v.y);
    if (len < 1e-8f) return (sfVector2f) { 0.f, 0.f };
    return (sfVector2f) { v.x / len, v.y / len };
}

/* Normale perpendiculaire à l'arête (a?b), orientée vers l'extérieur
   dans un repère SFML (Y vers le bas).
   On prend le vecteur perpendiculaire ( -(b.y-a.y), (b.x-a.x) ).   */
static sfVector2f EdgeNormal(sfVector2f a, sfVector2f b)
{
    sfVector2f edge = Vec2Sub(b, a);
    /* Perpendiculaire non normalisée */
    sfVector2f n = { -edge.y, edge.x };
    return Vec2Normalize(n);
}

/* Projette tous les sommets d'un polygone sur un axe.
   Retourne min et max dans *_min / *_max.                           */
static void ProjectPolygon(const SATPolygon* poly,
    sfVector2f axis,
    float* _min, float* _max)
{
    *_min = FLT_MAX;
    *_max = -FLT_MAX;
    for (int i = 0; i < poly->count; i++)
    {
        float p = Vec2Dot(poly->verts[i], axis);
        if (p < *_min) *_min = p;
        if (p > *_max) *_max = p;
    }
}

/* Calcule le centre (centroïde simple) d'un polygone.               */
static sfVector2f PolyCentroid(const SATPolygon* poly)
{
    sfVector2f c = { 0.f, 0.f };
    for (int i = 0; i < poly->count; i++)
    {
        c.x += poly->verts[i].x;
        c.y += poly->verts[i].y;
    }
    c.x /= poly->count;
    c.y /= poly->count;
    return c;
}

/* ???????????????????????????????????????????????????????????????????
   Construction de polygones
??????????????????????????????????????????????????????????????????? */

SATPolygon SAT_PolyFromTiled(const float* _verts, int _vertCount,
    float _ox, float _oy)
{
    SATPolygon p = { 0 };
    int n = _vertCount;
    if (n > SAT_MAX_VERTS) n = SAT_MAX_VERTS;
    p.count = n;

    /* Les vertices Tiled sont stockés comme x0,y0, x1,y1, ...
       et sont en coordonnées relatives à l'objet.
       On les passe en coordonnées monde × GAME_SCALE.               */
    for (int i = 0; i < n; i++)
    {
        p.verts[i].x = (_ox + _verts[i * 2]) * GAME_SCALE;
        p.verts[i].y = (_oy + _verts[i * 2 + 1]) * GAME_SCALE;
    }
    return p;
}

SATPolygon SAT_PolyFromRect(sfFloatRect r)
{
    return SAT_PolyFromBox(r.left, r.top, r.width, r.height);
}

SATPolygon SAT_PolyFromBox(float x, float y, float w, float h)
{
    SATPolygon p = { 0 };
    p.count = 4;
    /* Sens anti-horaire (haut-gauche ? haut-droit ? bas-droit ? bas-gauche) */
    p.verts[0] = (sfVector2f){ x,     y };
    p.verts[1] = (sfVector2f){ x + w, y };
    p.verts[2] = (sfVector2f){ x + w, y + h };
    p.verts[3] = (sfVector2f){ x,     y + h };
    return p;
}

SATPolygon SAT_Translate(SATPolygon poly, float dx, float dy)
{
    for (int i = 0; i < poly.count; i++)
    {
        poly.verts[i].x += dx;
        poly.verts[i].y += dy;
    }
    return poly;
}

/* ???????????????????????????????????????????????????????????????????
   Algorithme SAT
   ?????????????????????????????????????????????????????????????????
   Pour chaque arête des deux polygones :
     1. On calcule la normale de l'arête.
     2. On projette les deux polys sur cette normale.
     3. Si les projections ne se chevauchent pas ? pas de collision.
     4. Sinon on retient l'axe avec le plus petit chevauchement (MTV).
??????????????????????????????????????????????????????????????????? */

SATResult SAT_Test(const SATPolygon* a, const SATPolygon* b)
{
    SATResult res = { sfFalse, {0,0}, FLT_MAX, 0, 0 };

    float   minDepth = FLT_MAX;
    sfVector2f bestAxis = { 0.f, 1.f };

    /* ?? Axes issus de A ?? */
    for (int i = 0; i < a->count; i++)
    {
        int j = (i + 1) % a->count;
        sfVector2f axis = EdgeNormal(a->verts[i], a->verts[j]);

        float minA, maxA, minB, maxB;
        ProjectPolygon(a, axis, &minA, &maxA);
        ProjectPolygon(b, axis, &minB, &maxB);

        /* Séparation ? pas de collision */
        if (maxA <= minB || maxB <= minA)
            return res;   /* res.colliding = sfFalse */

        float overlap = (maxA < maxB) ? (maxA - minB) : (maxB - minA);
        if (overlap < minDepth)
        {
            minDepth = overlap;
            bestAxis = axis;
        }
    }

    /* ?? Axes issus de B ?? */
    for (int i = 0; i < b->count; i++)
    {
        int j = (i + 1) % b->count;
        sfVector2f axis = EdgeNormal(b->verts[i], b->verts[j]);

        float minA, maxA, minB, maxB;
        ProjectPolygon(a, axis, &minA, &maxA);
        ProjectPolygon(b, axis, &minB, &maxB);

        if (maxA <= minB || maxB <= minA)
            return res;

        float overlap = (maxA < maxB) ? (maxA - minB) : (maxB - minA);
        if (overlap < minDepth)
        {
            minDepth = overlap;
            bestAxis = axis;
        }
    }

    /* ?? Collision détectée ?? */
    res.colliding = sfTrue;
    res.depth = minDepth;

    /* S'assurer que la normale pointe de B vers A
       (du polygone statique vers l'entité mobile).                   */
    sfVector2f cA = PolyCentroid(a);
    sfVector2f cB = PolyCentroid(b);
    sfVector2f d = Vec2Sub(cA, cB);
    if (Vec2Dot(d, bestAxis) < 0.f)
    {
        bestAxis.x = -bestAxis.x;
        bestAxis.y = -bestAxis.y;
    }
    res.normal = bestAxis;

    /* Point de contact : milieu des centroïdes (approximation simple) */
    res.contactX = (cA.x + cB.x) * 0.5f;
    res.contactY = (cA.y + cB.y) * 0.5f;

    return res;
}

SATResult SAT_TestRect(const SATPolygon* poly, sfFloatRect rect)
{
    SATPolygon box = SAT_PolyFromRect(rect);
    return SAT_Test(poly, &box);
}

/* ???????????????????????????????????????????????????????????????????
   Résolution MTV
   ?????????????????????????????????????????????????????????????????
   Déplace _pos dans la direction de la normale MTV de la profondeur
   minimale pour sortir du polygone statique.
   Si la normale est suffisamment verticale (|ny| > 0.7) et pointe
   vers le haut (ny < 0) on considère l'entité comme au sol.
??????????????????????????????????????????????????????????????????? */

void SAT_Resolve(sfVector2f* pos, const SATResult* res, sfBool* onGround)
{
    if (!res->colliding) return;

    pos->x += res->normal.x * res->depth;
    pos->y += res->normal.y * res->depth;

    if (onGround)
    {
        /* normale.y < 0 ? pointe vers le haut ? on est au sol */
        *onGround = (res->normal.y < -0.7f) ? sfTrue : sfFalse;
    }
}

/* ???????????????????????????????????????????????????????????????????
   Debug : dessin du polygone
??????????????????????????????????????????????????????????????????? */

void SAT_DrawPolygon(sfRenderWindow* rw, const SATPolygon* poly, sfColor color)
{
    if (!poly || poly->count < 2) return;

    for (int i = 0; i < poly->count; i++)
    {
        int j = (i + 1) % poly->count;

        sfVertexArray* va = sfVertexArray_create();
        sfVertexArray_setPrimitiveType(va, sfLines);

        sfVertex v0, v1;
        v0.position = poly->verts[i];
        v0.color = color;
        v0.texCoords = (sfVector2f){ 0, 0 };

        v1.position = poly->verts[j];
        v1.color = color;
        v1.texCoords = (sfVector2f){ 0, 0 };

        sfVertexArray_append(va, v0);
        sfVertexArray_append(va, v1);

        sfRenderWindow_drawVertexArray(rw, va, NULL);
        sfVertexArray_destroy(va);
    }
}